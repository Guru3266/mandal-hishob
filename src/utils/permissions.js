// ============================================================
// USER ROLE
// ============================================================

export const getUserRole = () => {
  return localStorage.getItem("userRole") || "viewer";
};

// ============================================================
// ADMIN CHECK
// ============================================================

export const isAdmin = () => {
  return getUserRole() === "admin";
};

// ============================================================
// VIEWER CHECK
// ============================================================

export const isViewer = () => {
  return getUserRole() === "viewer";
};